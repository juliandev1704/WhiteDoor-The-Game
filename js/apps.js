// Lo que se ve en la pestaña "24/7"
function store247HTML(s) {
  const L = s.life;
  fxState(s);
  const act = L.fx.filter(f => f.until > s.day);
  let h = `<div class="fx-list">${act.length ? act.map(f => `<span class="fx-tag ${FX_INFO[f.id].good ? 'good' : 'bad'}">${FX_INFO[f.id].name} · ${Math.ceil(f.until - s.day)} día(s)</span>`).join('') : '<span class="muted">Sin efectos activos.</span>'}
    ${L.nic >= 1 ? `<span class="fx-tag bad">Dependencia a la nicotina: ${Math.round(L.nic)}</span>` : ''}</div>`;
  for (const sec of STORE_SECTIONS) {
    h += `<h3 class="store-sec">${iconImg(sec.icon)} ${sec.name}</h3><div class="grid">` + sec.ids.map(id => STORE247.find(x => x.id === id)).filter(Boolean).map(it =>
      `<div class="card">${iconImg(it.icon)}<div class="cinfo"><b>${it.name}</b><div class="muted">${it.desc}</div><div class="bonus">${it.side}</div></div>
      <div class="cbuy"><button class="btn primary small" data-buy247="${it.id}" ${s.money < it.price ? 'disabled' : ''}>${fmtMoney(it.price)}</button></div></div>`).join('') + '</div>';
  }
  return h;
}
function buy247(id) {
  const s = G.s, it = STORE247.find(x => x.id === id);
  if (!it || s.money < it.price) return;
  s.money -= it.price; it.use(s, s.needs); SFX.coin();
  UI.toast(`${it.name}: ${it.desc}`, 'good');
}

// La Tienda 24/7 (en la calle o en el celular) abre todo junto: 24/7 + Pixel Mall + Seguridad
UI.shop247 = function (tab = 'tienda') {
  if (tab === 'seguridad') return this.security();
  return this.mall(tab === 'tienda' ? '247' : tab, { store: true });
};
